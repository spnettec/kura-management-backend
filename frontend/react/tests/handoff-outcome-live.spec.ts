import { expect, test } from "@playwright/test";
import { readFileSync, writeFileSync } from "node:fs";
const b = process.env.KURA_HANDOFF_EVIDENCE_ROOT;
if (!b) throw new Error("explicit new ordinary handoff evidence root required");
const host = JSON.parse(readFileSync(`${b}/host-stack.json`, "utf8"));
const orb = JSON.parse(readFileSync(`${b}/orb.json`, "utf8"));
test("actual handoff original command resolves after native commit and test process exit", async ({ page }) => {
  test.setTimeout(300000);
  page.setDefaultTimeout(15000);
  page.on("requestfailed",r=>console.log("requestfailed",r.url(),r.failure()?.errorText));
  page.on("pageerror",e=>console.log("pageerror",e.message));
  expect(orb.state).toBe("completion-ready-awaiting-center");
  const requests: { operation: string; idempotencyKey:string }[] = [];
  page.on("request", r => { if (r.method() === "POST" && r.url().endsWith(`/gateways/${orb.gateway}/tasks`)) requests.push(r.postDataJSON()); });
  await page.goto("/login");
  console.log("step login page");
  await page.getByLabel("账号", { exact: true }).fill(host.testAdmin);
  await page.getByLabel("密码", { exact: true }).fill(readFileSync(`${host.fixture}/${host.testAdmin}.password`, "utf8"));
  await page.getByRole("button", { name: /登\s*录/ }).click();
  console.log("step login submitted");
  await page.getByRole("button", { name: `本轮普通配置中心交接 ${orb.gateway}`, exact: true }).click();
  console.log("step gateway opened");
  const panel = page.getByRole("region", { name: "Kura 普通配置交接", exact: true });
  const resume=process.env.KURA_HANDOFF_RESUME_PREPARE_TASK;
  if(resume){const session=await (await page.request.get("/api/v1/session")).json();await page.evaluate(({key,id})=>sessionStorage.setItem(key,id),{key:`yofc.handoff:${session.id}:${orb.gateway}:prepare`,id:resume});}
  await panel.getByRole("button", { name: "读取交接状态与原任务" }).click({timeout:90000});
  if(!resume){await expect(panel).toContainText("COMPLETED_APPROVED_CHECKS");
  await panel.getByRole("button", { name: "准备并审阅普通配置交接" }).click();}
  await expect(panel).toContainText(orb.ordinaryUnit, { timeout: 90000 });
  await expect(panel.getByRole("button", { name: "确认普通配置交接", exact: true })).toBeDisabled();
  const prepareId = resume ?? await panel.locator("p").filter({ hasText: "操作任务" }).locator("code").innerText();
  const original = await (await page.request.get(`/api/v1/tasks/${prepareId}`)).json();
  expect(original.result.checkIds).toContain("fixture.live-business");
  const prepareKey=process.env.KURA_HANDOFF_RESUME_PREPARE_KEY ?? requests.find(r=>r.operation==="recovery.ordinary.prepare")!.idempotencyKey;
  const recovered=await page.request.get(`/api/v1/gateways/${orb.gateway}/task-intents/${prepareKey}`);
  expect(recovered.status()).toBe(200);expect((await recovered.json()).id).toBe(prepareId);
  expect(await page.evaluate(() => Object.values(sessionStorage).join(" "))).not.toContain(original.result.confirmToken);
  // Restore only the authenticated original task; no replacement prepare.
  await page.reload();
  await page.getByRole("button", { name: `本轮普通配置中心交接 ${orb.gateway}`, exact: true }).click();
  await panel.getByRole("button", { name: "读取交接状态与原任务" }).click({timeout:90000});
  await expect(panel).toContainText(orb.ordinaryUnit);
  await expect(panel.getByRole("button", { name: "确认普通配置交接", exact: true })).toBeDisabled();
  await panel.getByRole("checkbox").check();
  const accepted = page.waitForResponse(r => r.status() === 202 && r.url().endsWith(`/gateways/${orb.gateway}/tasks`) && r.request().postDataJSON().operation === "recovery.ordinary.execute");
  await panel.getByRole("button", { name: "确认普通配置交接", exact: true }).click();
  const id: string = (await (await accepted).json()).id;
  writeFileSync(`${b}/center-execute-admitted.json`, JSON.stringify({ taskId:id, prepareId, exactlyOneExecuteRequest:requests.filter(r=>r.operation==="recovery.ordinary.execute").length===1 },null,2),{mode:0o600});
  const task = async () => (await page.request.get(`/api/v1/tasks/${id}`)).json();
  await expect.poll(async () => (await task()).state, {timeout:90000}).toBe("UNKNOWN");
  await expect(panel.getByRole("button",{name:"准备并审阅普通配置交接"})).toBeDisabled();
  writeFileSync(`${b}/awaiting-production.json`,JSON.stringify({state:"UNKNOWN",taskId:id,prepareId,executeRequests:requests.filter(r=>r.operation==="recovery.ordinary.execute").length},null,2),{mode:0o600});
  await expect.poll(async () => (await task()).state,{timeout:150000}).toBe("SUCCEEDED");
  const unknownObserved=true;
  const done = await task();
  expect(done.result.reconciliation.source).toBe("ordinary.handoff.journal.v1");
  expect(done.result.reconciliation.commandId).toBe(id);
  expect(done.result.id).toBe(original.result.transactionId);
  expect(done.result.ordinaryUnitHandedOff).toBe(true);
  expect(done.result.kuraRecoveryVerified).toBe(false);
  expect(done.result.normalBootVerified).toBe(false);
  expect(done.result.report.schema).toBe(2);
  expect(done.result.report.processId).toBeGreaterThan(0);
  expect(done.result.report.checks.every((v:{passed:boolean})=>v.passed)).toBe(true);
  expect(requests.filter(r=>r.operation==="recovery.ordinary.execute")).toHaveLength(1);
  expect(requests.filter(r=>r.operation==="recovery.ordinary.prepare")).toHaveLength(resume?0:1);
  await page.goto("/commands");
  await page.getByRole("button",{name:new RegExp(`执行普通配置交接 ${id.slice(0,8)}`)}).click();
  const detail=page.getByRole("dialog");
  await expect(detail).toContainText("不代表完整业务恢复或重启验收");
  await expect(detail.getByText("已依据原命令的普通交接决定核定",{exact:true})).toBeVisible();
  await detail.waitFor({state:"visible"});
  await page.screenshot({path:`${b}/center-handoff-zh.png`,fullPage:true,animations:"disabled"});
  await detail.getByRole("combobox",{name:"语言 / Language"}).selectOption("en-US");
  await expect(detail).toContainText("without certifying full recovery or reboot");
  await expect(detail.getByText("Reconciled from the original ordinary handoff decision",{exact:true})).toBeVisible();
  await page.screenshot({path:`${b}/center-handoff-en.png`,fullPage:true,animations:"disabled"});
  writeFileSync(`${b}/center-browser-live.json`,JSON.stringify({status:"passed",gateway:orb.gateway,prepareId,executeTaskId:id,unknownObserved,originalIntentReadbackPassed:true,prepareKey,actualHttpsGrpcAgent:true,browserExecuteRequests:1,replacementPrepareRequests:0,bilingual:true,ordinaryPid:done.result.report.processId,scope:done.result.scope,kuraRecoveryVerified:false,normalBootVerified:false},null,2));
});

test.afterEach(async ({page},info)=>{if(info.status!==info.expectedStatus){writeFileSync(`${b}/live-failure-body-v2.txt`,await page.locator("body").innerText(),{mode:0o600});await page.screenshot({path:`${b}/live-failure-v2.png`,fullPage:true});}});
